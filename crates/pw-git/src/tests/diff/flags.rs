//! 생성 파일 표시와 대용량(M2-04 완료 기준 ② · ③): `Cargo.lock` 과 `linguist-generated` 파일에 생성 표시가 붙고, 50 MiB 넘는
//! 파일은 hunk 를 만들지 않고 객체 저장소에서 푼 바이트가 기준 이하다.

use pw_fs::limits::READ_ONLY_MAX;

use super::*;
use crate::diff::changes::{Stats, diff};

#[test]
fn cargo_lock_and_linguist_generated_files_are_marked_generated() {
    let r = TestRepo::with_commit();
    r.write(
        ".gitattributes",
        "gen/** linguist-generated\nlocked/Cargo.lock -linguist-generated\n",
    );
    r.commit_all("attributes");
    for (path, text) in [
        ("Cargo.lock", "version = 3\n"),
        ("locked/Cargo.lock", "version = 3\n"),
        ("gen/out.txt", "made by a tool\n"),
        ("src/main.rs", "fn main() {}\n"),
        // 내용 규칙(앞부분을 본다 — 결정 M1-D20 대안 ①).
        (
            "lib/app.js",
            "// Generated by CoffeeScript 1.12.7\nvar x = 1;\n",
        ),
        ("lib/hand.js", "// written by hand\nvar x = 1;\n"),
    ] {
        r.write(path, text);
    }
    r.commit_all("files");
    let repo = Repo::new(r);
    let diff = repo.diff(None, commit("HEAD"));
    let marked: Vec<(&str, bool)> = diff
        .files
        .iter()
        .map(|f| (f.path.as_str(), f.generated))
        .collect();
    assert_eq!(
        marked,
        [
            ("Cargo.lock", true),
            ("gen/out.txt", true),
            ("lib/app.js", true),
            ("lib/hand.js", false),
            ("locked/Cargo.lock", false),
            ("src/main.rs", false),
        ]
    );
}

fn opened(repo: &Repo) -> crate::Opened {
    repo.f.git.open(&repo.id, None).unwrap().unwrap()
}

/// 50 MiB 를 1바이트 넘는 텍스트 파일.
fn big_text(tail: &str) -> String {
    let line = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcde\n";
    let mut text = line.repeat(READ_ONLY_MAX as usize / line.len() + 1);
    text.truncate(READ_ONLY_MAX as usize + 1 - tail.len());
    text.push_str(tail);
    assert_eq!(text.len() as u64, READ_ONLY_MAX + 1);
    text
}

#[test]
fn a_file_over_fifty_mib_gets_no_hunks_and_its_content_is_not_read() {
    let r = TestRepo::with_commit();
    r.write("big.txt", &big_text("a\n"));
    r.write("small.txt", "small\n");
    r.commit_all("big");
    r.write("big.txt", &big_text("b\n"));
    r.write("small.txt", "smaller\n");
    r.commit_all("edit");
    let repo = Repo::new(r);
    let opened = opened(&repo);

    let stats = Stats::default();
    let got = diff(&opened, &repo.params(None, commit("HEAD")), &stats).unwrap();
    let big = got.files.iter().find(|f| f.path == "big.txt").unwrap();
    assert!(
        big.too_large && !big.binary && big.hunks.is_empty(),
        "{big:?}"
    );
    let small = got.files.iter().find(|f| f.path == "small.txt").unwrap();
    assert!(!small.too_large && !small.hunks.is_empty());
    // 작은 파일의 두 쪽만 풀었다 — 큰 파일은 헤더만 봤다.
    let read = stats
        .object_bytes
        .load(std::sync::atomic::Ordering::Relaxed);
    assert_eq!(read, ("small\n".len() + "smaller\n".len()) as u64);
    assert!(read <= READ_ONLY_MAX);

    // 작업 트리 쪽은 파일 크기만 본다(index 쪽 blob 도 풀지 않는다).
    repo.r.write("big.txt", &big_text("c\n"));
    let stats = Stats::default();
    let got = diff(&opened, &repo.params(None, DiffSide::WorkTree), &stats).unwrap();
    assert_eq!(got.files.len(), 1);
    assert!(got.files[0].too_large && got.files[0].hunks.is_empty());
    assert_eq!(
        stats
            .object_bytes
            .load(std::sync::atomic::Ordering::Relaxed),
        0
    );

    // `git.blob` 도 풀지 않고 크기만 준다.
    let blob = repo.blob(Some("HEAD"), "big.txt");
    assert_eq!(
        (blob.too_large, blob.size, blob.content, blob.judgment),
        (true, READ_ONLY_MAX + 1, None, None)
    );
}
