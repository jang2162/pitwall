//! `rpc_method!` 선언에서 TS 타입과 JSON Schema 를 만든다(`docs/design/02-tech-stack.md` §2.6).
//!
//! 실행 파일 둘이 이 라이브러리를 쓴다. 둘 다 `--check` 를 주면 쓰지 않고 디스크의 파일과 비교만 한다.
//! - `pw-rpc-gen`: 링크된 크레이트의 선언 전부([`pw_rpc::methods`]) → `packages/rpc-client/src/generated/`
//! - `pw-rpc-gen-fixtures`: 시험용 선언과 골든 메시지 → `packages/rpc-client/test/fixtures/`
//!
//! 생성물은 oxfmt 가 포맷하지 않는다(`.oxfmtrc.json` 의 ignorePatterns). 포맷하면 `--check` 가 생성기 출력과
//! 디스크를 바이트로 비교할 수 없다 — 생성기 출력이 곧 커밋되는 형태여야 한다.

use std::borrow::Cow;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use pw_rpc::protocol::NAMES;
use pw_rpc::{MethodInfo, MethodKind, RESERVED_PREFIXES, code};
use schemars::generate::SchemaSettings;
use schemars::{Schema, SchemaGenerator};
use serde_json::{Map, Value, json};
use specta::Types;
use specta::datatype::DataType;
use specta_typescript::{Exporter, Typescript};

/// 재생성 명령. 생성물 머리에 적힌다.
pub const REGENERATE: &str = "mise run gen";

/// 저장소 루트. 생성물 경로의 기준이다.
pub fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

/// TS 파일 하나: 내장 프로토콜 타입 + 메서드 맵 + 메타데이터 · 프로토콜 상수.
///
/// `methods` 의 입출력 타입과 그 타입이 참조하는 이름 있는 타입이 모두 들어간다.
pub fn typescript(methods: &[&MethodInfo]) -> Result<String, specta_typescript::Error> {
    let mut types = Types::default();
    register_protocol(&mut types);

    let entries: Vec<MethodTypes> = methods
        .iter()
        .map(|info| MethodTypes {
            name: info.meta.name,
            kind: info.meta.kind,
            doc: info.meta.doc,
            meta: serde_json::to_string(&info.meta).expect("MethodMeta serializes"),
            params: info.params_type(&mut types),
            output: info.output_type(&mut types),
        })
        .collect();

    let exporter: Exporter = Typescript::default().into();
    let exporter = exporter
        .framework_prelude(format!(
            "// @generated by pw-rpc-gen from the `rpc_method!` declarations. Do not edit.\n\
             // Regenerate: {REGENERATE}"
        ))
        .framework_runtime(move |fe| render_runtime(&fe, &entries).map(Cow::Owned));
    Typescript::from(exporter).export(&types, specta_serde::Format)
}

/// 클라이언트가 쓰는 내장 프로토콜 타입. 메서드가 참조하지 않아도 항상 내보낸다.
fn register_protocol(types: &mut Types) {
    use pw_rpc::protocol::*;
    use pw_rpc::*;
    types
        .register_mut::<JsonValue>()
        .register_mut::<Id>()
        .register_mut::<JsonRpcVersion>()
        .register_mut::<RequestMessage>()
        .register_mut::<ResponseMessage<'static>>()
        .register_mut::<NotificationMessage<'static>>()
        .register_mut::<RpcError>()
        .register_mut::<Tier>()
        .register_mut::<Role>()
        .register_mut::<MethodKind>()
        .register_mut::<MethodMeta>()
        .register_mut::<CancelRequestParams>()
        .register_mut::<StreamCreditParams>()
        .register_mut::<StreamCancelParams>()
        .register_mut::<StreamOpened>()
        .register_mut::<StreamChunk>()
        .register_mut::<StreamEnd>()
        .register_mut::<StreamOutcome>()
        .register_mut::<SubscribeParams>()
        .register_mut::<Subscribed>()
        .register_mut::<UnsubscribeParams>()
        .register_mut::<EventMessage>();
}

struct MethodTypes {
    name: &'static str,
    kind: MethodKind,
    doc: &'static str,
    meta: String,
    params: DataType,
    output: DataType,
}

fn render_runtime(
    fe: &specta_typescript::FrameworkExporter<'_>,
    entries: &[MethodTypes],
) -> Result<String, specta_typescript::Error> {
    // 이름 있는 타입은 이름으로 가리킨다. inline 은 참조도 본문으로 펼친다.
    let ts = |dt: &DataType| match dt {
        DataType::Reference(r) => fe.reference(r),
        other => fe.inline(other),
    };
    let mut out = String::new();
    for (kind, title, output_key) in [
        (MethodKind::Unary, "UnaryMethods", "result"),
        (MethodKind::Stream, "StreamMethods", "item"),
    ] {
        let of_kind: Vec<_> = entries.iter().filter(|e| e.kind == kind).collect();
        let _ = writeln!(
            out,
            "/** 선언된 {} 메서드: 이름 → 입력 · {output_key} 타입. */",
            kind_name(kind)
        );
        if of_kind.is_empty() {
            let _ = writeln!(out, "export type {title} = Record<never, never>;\n");
            continue;
        }
        let _ = writeln!(out, "export type {title} = {{");
        for e in of_kind {
            out += &jsdoc(e.doc, "\t");
            let _ = writeln!(
                out,
                "\t{name:?}: {{ params: {params}; {output_key}: {output} }};",
                name = e.name,
                params = ts(&e.params)?,
                output = ts(&e.output)?,
            );
        }
        out += "};\n\n";
    }
    out += "export type MethodName = keyof UnaryMethods | keyof StreamMethods;\n\n";

    out += "/** 메서드 메타데이터(권한 등급 · role · 문서). */\n";
    out += "export const METHODS: Record<MethodName, MethodMeta> = {\n";
    for e in entries {
        let _ = writeln!(out, "\t{:?}: {},", e.name, e.meta);
    }
    out += "};\n\n";

    out += "/** 내장 프로토콜 메서드 이름. */\nexport const PROTOCOL = {\n";
    for (name, value) in NAMES {
        let _ = writeln!(out, "\t{name}: {value:?},");
    }
    out += "} as const;\n\n";

    out += "/** 오류 코드. 애플리케이션 코드는 -32768..=-32000 밖에서 고른다. */\nexport const ERROR_CODE = {\n";
    for (name, value) in code::ALL {
        let _ = writeln!(out, "\t{name}: {value},");
    }
    out += "} as const;\n\n";

    let prefixes: Vec<String> = RESERVED_PREFIXES.iter().map(|p| format!("{p:?}")).collect();
    let _ = writeln!(
        out,
        "/** 선언한 메서드가 쓸 수 없는 접두사. */\nexport const RESERVED_PREFIXES = [{}] as const;",
        prefixes.join(", ")
    );
    Ok(out)
}

fn kind_name(kind: MethodKind) -> &'static str {
    match kind {
        MethodKind::Unary => "unary",
        MethodKind::Stream => "stream",
    }
}

fn jsdoc(doc: &str, indent: &str) -> String {
    let lines: Vec<&str> = doc
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty())
        .collect();
    if lines.is_empty() {
        return String::new();
    }
    let mut out = format!("{indent}/**\n");
    for line in lines {
        let _ = writeln!(out, "{indent} * {}", line.replace("*/", "*\\/"));
    }
    out + &format!("{indent} */\n")
}

/// JSON Schema 파일: 메서드마다 입력(`params`)과 출력(`result` · `item`)의 독립 스키마(draft 2020-12).
///
/// 입력은 역직렬화, 출력은 직렬화 기준으로 만든다(serde 속성이 방향마다 다를 수 있다).
/// 각 스키마는 자기 `$defs` 를 갖는다 — MCP 툴의 `inputSchema` 로 그대로 쓸 수 있게.
pub fn json_schema(methods: &[&MethodInfo]) -> String {
    let mut out = Map::new();
    for info in methods {
        let meta = &info.meta;
        let output_key = match meta.kind {
            MethodKind::Unary => "result",
            MethodKind::Stream => "item",
        };
        let params = standalone(SchemaSettings::draft2020_12().for_deserialize(), |g| {
            info.params_schema(g)
        });
        let output = standalone(SchemaSettings::draft2020_12().for_serialize(), |g| {
            info.output_schema(g)
        });
        out.insert(
            meta.name.to_owned(),
            json!({
                "kind": meta.kind,
                "tier": meta.tier,
                "roles": meta.roles,
                "description": meta.doc.lines().map(str::trim).collect::<Vec<_>>().join("\n").trim(),
                "params": params,
                output_key: output,
            }),
        );
    }
    let doc = json!({
        "$comment": format!("@generated by pw-rpc-gen from the `rpc_method!` declarations. Do not edit. Regenerate: {REGENERATE}"),
        "methods": out,
    });
    serde_json::to_string_pretty(&doc).expect("schema serializes") + "\n"
}

/// 하위 스키마 하나를 `$defs` 를 품은 루트 스키마로 만든다. 루트가 `$ref` 하나면 그 정의를 펼친다.
fn standalone(
    settings: SchemaSettings,
    subschema: impl FnOnce(&mut SchemaGenerator) -> Schema,
) -> Value {
    let meta_schema = settings.meta_schema.clone();
    let mut generator = settings.into_generator();
    let schema = subschema(&mut generator);
    let mut defs = generator.take_definitions(true);
    let mut root = match schema
        .as_object()
        .and_then(|o| o.get("$ref"))
        .and_then(Value::as_str)
    {
        Some(r) => r
            .strip_prefix("#/$defs/")
            .and_then(|name| defs.remove(name))
            .unwrap_or_else(|| schema.to_value()),
        None => schema.to_value(),
    };
    if let Value::Object(obj) = &mut root {
        if let Some(meta_schema) = meta_schema {
            obj.insert("$schema".into(), Value::String(meta_schema.into_owned()));
        }
        if !defs.is_empty() {
            obj.insert("$defs".into(), Value::Object(defs));
        }
    }
    root
}

/// 생성물 하나.
pub struct Output {
    /// 저장소 루트 기준 경로.
    pub path: &'static str,
    pub contents: String,
}

/// 인자에 `--check` 가 있으면 디스크의 파일과 비교만 하고, 없으면 쓴다.
pub fn emit(outputs: &[Output]) -> ExitCode {
    let check = std::env::args().skip(1).any(|a| a == "--check");
    let root = repo_root();
    let mut stale = Vec::new();
    for output in outputs {
        let path = root.join(output.path);
        if check {
            if std::fs::read_to_string(&path).ok().as_deref() != Some(output.contents.as_str()) {
                stale.push(output.path);
            }
            continue;
        }
        if let Some(dir) = path.parent()
            && let Err(e) = std::fs::create_dir_all(dir)
        {
            eprintln!("pw-rpc-gen: cannot create {}: {e}", dir.display());
            return ExitCode::FAILURE;
        }
        if let Err(e) = std::fs::write(&path, &output.contents) {
            eprintln!("pw-rpc-gen: cannot write {}: {e}", path.display());
            return ExitCode::FAILURE;
        }
    }
    if stale.is_empty() {
        return ExitCode::SUCCESS;
    }
    eprintln!(
        "pw-rpc-gen: generated files are out of date — run `{REGENERATE}` and commit the result:"
    );
    for path in stale {
        eprintln!("  {path}");
    }
    ExitCode::FAILURE
}

/// 생성 실패를 사람이 읽을 메시지로 바꾼다. specta 의 오류는 어느 타입 · 필드인지 담고 있다.
pub fn or_exit<T>(result: Result<T, specta_typescript::Error>) -> Result<T, ExitCode> {
    result.map_err(|e| {
        eprintln!("pw-rpc-gen: TypeScript export failed:\n{e}");
        ExitCode::FAILURE
    })
}

#[cfg(test)]
mod tests {
    use pw_rpc::rpc_method;
    use serde::{Deserialize, Serialize};

    use super::*;

    #[derive(Serialize, Deserialize, specta::Type, schemars::JsonSchema)]
    #[serde(rename_all = "camelCase")]
    pub struct Outer {
        pub inner: Inner,
        pub max_rows: Option<u32>,
    }

    #[derive(Serialize, Deserialize, specta::Type, schemars::JsonSchema)]
    pub struct Inner {
        pub path: String,
    }

    rpc_method! {
        /// 첫 줄.
        /// 주석을 닫는 */ 도 안전하다.
        pub Query: "gen.query" { params: Outer, result: Vec<Inner>, tier: Write }
    }

    fn query() -> MethodInfo {
        MethodInfo::unary::<Query>()
    }

    #[test]
    fn schema_inlines_the_root_and_keeps_nested_defs() {
        let doc: Value = serde_json::from_str(&json_schema(&[&query()])).unwrap();
        let method = &doc["methods"]["gen.query"];
        assert_eq!(method["tier"], "write");
        assert_eq!(method["roles"], json!(["owner"]));
        assert_eq!(method["description"], "첫 줄.\n주석을 닫는 */ 도 안전하다.");

        let params = &method["params"];
        assert_eq!(
            params["$schema"],
            "https://json-schema.org/draft/2020-12/schema"
        );
        assert_eq!(params["type"], "object");
        assert_eq!(params["required"], json!(["inner"]));
        assert_eq!(params["properties"]["inner"]["$ref"], "#/$defs/Inner");
        assert!(params["$defs"]["Inner"].is_object());
        assert!(
            params["$defs"].get("Outer").is_none(),
            "the root is inlined"
        );

        let result = &method["result"];
        assert_eq!(result["type"], "array");
        assert_eq!(result["items"]["$ref"], "#/$defs/Inner");
    }

    #[test]
    fn typescript_maps_method_names_to_named_types() {
        let ts = typescript(&[&query()]).unwrap();
        assert!(ts.starts_with("// @generated by pw-rpc-gen"), "{ts}");
        assert!(
            ts.contains("\"gen.query\": { params: Outer; result: Inner[] };"),
            "{ts}"
        );
        assert!(ts.contains("export type StreamMethods = Record<never, never>;"));
        assert!(ts.contains("maxRows: number | null"), "{ts}");
        // JSDoc 안의 `*/` 만 막는다. METHODS 의 문자열 리터럴 안에서는 그대로여도 된다.
        assert!(ts.contains(" * 주석을 닫는 *\\/ 도"), "{ts}");
        assert!(!ts.contains(" * 주석을 닫는 */"), "{ts}");
        // 메서드가 참조하지 않아도 프로토콜 타입은 항상 나간다.
        assert!(ts.contains("export type StreamEnd = "), "{ts}");
    }
}
